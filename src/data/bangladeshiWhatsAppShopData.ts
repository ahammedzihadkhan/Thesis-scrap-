/**
 * Helper to compute comprehensive business KPIs for the Omni-Channel Retail, POS, E-Commerce & Social Shop
 */
export function computeWhatsAppShopKPIs(orders: FCommerceOrder[]): WhatsAppShopKPIs {
  if (orders.length === 0) {
    return {
      totalRevenueBDT: 0,
      totalOrders: 0,
      uniqueCustomers: 0,
      repeatCustomers: 0,
      repeatCustomerRatePct: 0,
      avgOrderValueBDT: 0,
      prepaidRevenueBDT: 0,
      prepaidCount: 0,
      prepaidSharePct: 0,
      codCount: 0,
      codSharePct: 0,
      codRevenueBDT: 0,
      rtoCount: 0,
      rtoRatePct: 0,
      rtoLostRevenueBDT: 0,
      advanceCollectedBDT: 0,
      whatsappOrderCount: 0,
      smsReachableCount: 0,
      emailReachableCount: 0,
      messengerOrderCount: 0,
      missingPhoneCount: 0,
      missingPhoneSharePct: 0,
    };
  }

  const totalOrders = orders.length;
  let totalRevenueBDT = 0;
  let prepaidRevenueBDT = 0;
  let prepaidCount = 0;
  let codCount = 0;
  let codRevenueBDT = 0;
  let rtoCount = 0;
  let rtoLostRevenueBDT = 0;
  let advanceCollectedBDT = 0;
  let whatsappOrderCount = 0;
  let smsReachableCount = 0;
  let emailReachableCount = 0;
  let messengerOrderCount = 0;
  let missingPhoneCount = 0;

  const customerOrderCounts = new Map<string, number>();

  orders.forEach((o) => {
    totalRevenueBDT += o.totalAmountBDT;
    advanceCollectedBDT += o.advancePaidBDT;

    const hasWaPhone = !!o.whatsappPhone && o.whatsappPhone.trim().length > 6;
    const hasSmsPhone = (!!o.smsPhone && o.smsPhone.trim().length > 6) || hasWaPhone;
    const hasEmail = !!o.customerEmail && o.customerEmail.includes('@');
    const hasMessenger = !!o.facebookProfileId && o.facebookProfileId.trim().length > 2;

    if (o.preferredChannel === 'sms') {
      smsReachableCount++;
    } else if (o.preferredChannel === 'email') {
      emailReachableCount++;
    } else if (o.preferredChannel === 'messenger' || (!hasWaPhone && !hasSmsPhone && hasMessenger)) {
      messengerOrderCount++;
      missingPhoneCount++;
    } else if (hasWaPhone) {
      whatsappOrderCount++;
    } else if (hasSmsPhone) {
      smsReachableCount++;
    } else if (hasEmail) {
      emailReachableCount++;
    } else {
      messengerOrderCount++;
      missingPhoneCount++;
    }

    // Unified customer key for deduplication across Phone, Email, and Social ID
    const anyPhone = o.whatsappPhone || o.smsPhone;
    const key = anyPhone && anyPhone.trim().length > 6
      ? anyPhone.replace(/[^\d]/g, '')
      : (o.customerEmail || o.facebookProfileId || o.customerName.toLowerCase().trim());
    customerOrderCounts.set(key, (customerOrderCounts.get(key) || 0) + 1);

    // Payment classification
    const isPrepaid =
      o.paymentMethod.includes('bKash') ||
      o.paymentMethod.includes('Nagad') ||
      o.paymentMethod.includes('Bank');

    if (isPrepaid) {
      prepaidCount++;
      prepaidRevenueBDT += o.totalAmountBDT;
    } else {
      codCount++;
      codRevenueBDT += o.totalAmountBDT;
    }

    // RTO tracking
    if (o.deliveryStatus === 'RTO / Returned') {
      rtoCount++;
      rtoLostRevenueBDT += o.totalAmountBDT;
    }
  });

  const uniqueCustomers = customerOrderCounts.size;
  let repeatCustomers = 0;
  customerOrderCounts.forEach((count) => {
    if (count > 1) repeatCustomers++;
  });

  const repeatCustomerRatePct = uniqueCustomers > 0 ? (repeatCustomers / uniqueCustomers) * 100 : 0;
  const avgOrderValueBDT = totalOrders > 0 ? Math.round(totalRevenueBDT / totalOrders) : 0;
  const prepaidSharePct = totalOrders > 0 ? (prepaidCount / totalOrders) * 100 : 0;
  const codSharePct = totalOrders > 0 ? (codCount / totalOrders) * 100 : 0;
  const rtoRatePct = totalOrders > 0 ? (rtoCount / totalOrders) * 100 : 0;
  const missingPhoneSharePct = totalOrders > 0 ? (missingPhoneCount / totalOrders) * 100 : 0;

  return {
    totalRevenueBDT,
    totalOrders,
    uniqueCustomers,
    repeatCustomers,
    repeatCustomerRatePct,
    avgOrderValueBDT,
    prepaidRevenueBDT,
    prepaidCount,
    prepaidSharePct,
    codCount,
    codSharePct,
    codRevenueBDT,
    rtoCount,
    rtoRatePct,
    rtoLostRevenueBDT,
    advanceCollectedBDT,
    whatsappOrderCount,
    smsReachableCount,
    emailReachableCount,
    messengerOrderCount,
    missingPhoneCount,
    missingPhoneSharePct,
  };
}

/**
 * Builds direct WhatsApp chat URL
 */
export function buildWhatsAppChatUrl(
  phone: string,
  templateType: 'order_confirm' | 'courier_dispatch' | 'eid_offer' | 'review_request' | 'personalized_offer',
  params: {
    customerName: string;
    items?: string;
    totalAmountBDT?: number;
    advancePaidBDT?: number;
    dueAmountBDT?: number;
    trackingNumber?: string;
    courierPartner?: string;
    promoCode?: string;
    discountPct?: number;
    suggestedProduct?: string;
    discountedPrice?: number;
    customMessage?: string;
    lang?: 'bn' | 'en';
  }
): string {
  const e164 = formatE164Phone(phone);
  const cleanPhone = e164 ? e164.replace('+', '') : phone.replace(/[^\d]/g, '');
  const message = buildMessageCopy(templateType, params);
  const encoded = encodeURIComponent(message);
  return `https://wa.me/${cleanPhone}?text=${encoded}`;
}

