/**
 * Converts generic RawTransaction rows (from POS Systems, Daraz BD, Pickaboo, WooCommerce, Shopify, or Excel)
 * into standardized Omni-Channel FCommerceOrder objects with 4-channel fallback (WhatsApp, Phone SMS, Email, Messenger).
 */
const BD_DISTRICTS_FALLBACK = [
  'Dhaka (Uttara)',
  'Dhaka (Dhanmondi)',
  'Dhaka (Mirpur)',
  'Dhaka (Gulshan)',
  'Chattogram (Agrabad)',
  'Sylhet (Zindabazar)',
  'Rajshahi (Shaheb Bazar)',
  'Khulna (Sonadanga)',
  'Cumilla (Kandirpar)',
  'Gazipur (Tongi)',
];

const BD_COURIERS_FALLBACK = [
  'Pathao Courier',
  'Steadfast',
  'RedX',
  'Paperfly',
  'Sundarban Courier',
];

export function convertRawRowsToWhatsAppShopOrders(rows: RawTransaction[]): FCommerceOrder[] {
  return rows.map((r, idx) => {
    const rawWaPhoneVal =
      r['WhatsApp Phone'] ??
      r.whatsapp_phone ??
      r.WhatsAppPhone ??
      '';
    const rawSmsPhoneVal =
      r['Phone (SMS/POS)'] ??
      r.sms_phone ??
      r['Customer Phone'] ??
      r['Shipping Phone Number'] ??
      r.phone ??
      r.mobile ??
      rawWaPhoneVal ??
      '';
    const rawWaPhone = String(rawWaPhoneVal).replace(/^N\/A.*$/i, '').trim();
    const rawSmsPhone = String(rawSmsPhoneVal).replace(/^N\/A.*$/i, '').trim();
    const anyPhone = rawWaPhone || rawSmsPhone;

    const rawEmailVal =
      r['Customer Email'] ??
      r.customer_email ??
      r.CustomerEmail ??
      r.email ??
      r.Email ??
      '';
    const rawEmail = String(rawEmailVal).replace(/^N\/A.*$/i, '').trim();

    const rawHandleVal =
      r['Facebook Profile / Messenger'] ??
      r.facebook_id ??
      r.messenger_id ??
      r.facebookProfileId ??
      r.FacebookProfileId ??
      r.messenger ??
      r.m_me ??
      '';
    const rawHandle = String(rawHandleVal).replace(/^N\/A.*$/i, '').trim();

    const orderId = String(
      r['Order ID'] ||
      r.order_id ||
      r['Order Number'] ||
      r.id ||
      r.InvoiceNo ||
      `ORD-${1000 + idx}`
    );

    const orderDate = String(
      r['Order Date'] ||
      r.order_date ||
      r['Created at'] ||
      r.created_at ||
      r.InvoiceDate ||
      r.date ||
      new Date().toISOString().slice(0, 10)
    );

    const customerName = String(
      r['Customer Name'] ||
      r.customer_name ||
      r.CustomerName ||
      r['Recipient Name'] ||
      r.buyer_name ||
      r.name ||
      'Customer ' + (idx + 1)
    );

    const items = String(
      r['Items / Products'] ||
      r['Items Ordered'] ||
      r.items ||
      r['Item Name'] ||
      r.product_name ||
      r['Product Title'] ||
      r.Description ||
      r.sku ||
      'Store Item'
    );

    const category = String(
      r.Category ||
      r.category ||
      r.brand ||
      r.Brand ||
      r['Product Category'] ||
      'General'
    );

    const quantity = Number(r.Quantity || r.quantity || r.Qty) || 1;
    const parsedUnitPrice = Number(r['Unit Price (BDT)'] || r.unit_price || r.UnitPrice || r['Item Price'] || r['Paid Price'] || r.price);
    const parsedTotal = Number(r['Total Amount (BDT)'] || r.total_price || r.total_amount || r.TotalAmount || r['Total Price'] || r.total);

    const unitPrice = !isNaN(parsedUnitPrice) && parsedUnitPrice > 0
      ? parsedUnitPrice
      : (!isNaN(parsedTotal) && parsedTotal > 0 ? parsedTotal / quantity : 500);

    const totalAmountBDT = !isNaN(parsedTotal) && parsedTotal > 0
      ? parsedTotal
      : unitPrice * quantity;

    const rawChannelStr = String(r.channel || r['Channel'] || r.OrderChannel || '').trim();
    const rawChannelLower = rawChannelStr.toLowerCase();
    const explicitPref = String(r.preferred_channel || r['Preferred Reach'] || '').toLowerCase();

    const rawStatus = String(r['Delivery Status'] || r.delivery_status || r.DeliveryStatus || r.status || r['Order Status'] || 'Delivered').toLowerCase();
    let deliveryStatus: FCommerceOrder['deliveryStatus'] = 'Delivered';
    if (rawStatus.includes('return') || rawStatus.includes('rto') || rawStatus.includes('cancel')) {
      deliveryStatus = 'RTO / Returned';
    } else if (rawStatus.includes('transit') || rawStatus.includes('shipped') || rawStatus.includes('way')) {
      deliveryStatus = 'In Transit';
    } else if (rawStatus.includes('pending') || rawStatus.includes('process') || rawStatus.includes('confirm')) {
      deliveryStatus = 'Pending Confirmation';
    }

    const explicitPayment = String(r['Payment Method'] || r.payment_method || r.PaymentMethod || r.payment_type || '').toLowerCase();
    let paymentMethod: FCommerceOrder['paymentMethod'] = 'Cash on Delivery (COD)';
    if (explicitPayment) {
      if (explicitPayment.includes('bkash')) {
        paymentMethod = explicitPayment.includes('merchant') ? 'bKash Merchant' : 'bKash Personal';
      } else if (explicitPayment.includes('nagad')) {
        paymentMethod = 'Nagad';
      } else if (explicitPayment.includes('bank') || explicitPayment.includes('card') || explicitPayment.includes('online')) {
        paymentMethod = 'Bank Transfer';
      } else {
        paymentMethod = 'Cash on Delivery (COD)';
      }
    } else {
      // Deterministic realistic payment mix when CSV omits payment_method column (e.g. Daraz/Pickaboo/POS export)
      const mod = idx % 10;
      if (mod === 0 || mod === 3) paymentMethod = 'bKash Merchant';
      else if (mod === 1) paymentMethod = 'bKash Personal';
      else if (mod === 4) paymentMethod = 'Nagad';
      else if (mod === 8) paymentMethod = 'Bank Transfer';
      else paymentMethod = 'Cash on Delivery (COD)';
    }

    const explicitAdvance = r['Advance Paid (BDT)'] ?? r.advance_paid ?? r.AdvancePaid;
    let advancePaidBDT = 0;
    if (explicitAdvance !== undefined && explicitAdvance !== '') {
      advancePaidBDT = Number(explicitAdvance) || 0;
    } else {
      if (paymentMethod !== 'Cash on Delivery (COD)') {
        advancePaidBDT = totalAmountBDT;
      } else {
        advancePaidBDT = idx % 3 === 0 ? Math.min(150, totalAmountBDT) : 0;
      }
    }

    const dueAmountBDT = Math.max(0, totalAmountBDT - advancePaidBDT);
    const deliveryDistrict = String(
      r['Delivery District / Area'] ||
      r['Delivery District'] ||
      r.delivery_district ||
      r.DeliveryDistrict ||
      r.district ||
      r.city ||
      BD_DISTRICTS_FALLBACK[idx % BD_DISTRICTS_FALLBACK.length]
    );
    const courierPartner = (
      r['Courier Partner'] ||
      r.courier_partner ||
      r.CourierPartner ||
      (rawChannelStr.includes('Pickaboo')
        ? 'Pickaboo Express'
        : BD_COURIERS_FALLBACK[idx % BD_COURIERS_FALLBACK.length])
    ) as any;
    const trackingNumber = String(
      r['Tracking Number'] ||
      r['Courier Tracking No'] ||
      r.tracking_number ||
      r.TrackingNumber ||
      `TRK-${100000 + idx}`
    );
    const customerNotes = String(r['Customer Notes'] || r.CustomerNotes || r.notes || '');

    const hasPhone = Boolean(anyPhone && anyPhone.length > 5);
    const hasEmail = Boolean(rawEmail && rawEmail.includes('@'));

    let orderChannel: FCommerceOrder['orderChannel'] = 'WhatsApp';
    let preferredChannel: FCommerceOrder['preferredChannel'] = 'whatsapp';
    let finalWaPhone: string | undefined = hasPhone ? anyPhone : undefined;
    let finalSmsPhone: string | undefined = hasPhone ? anyPhone : undefined;
    let finalEmail: string | undefined = hasEmail ? rawEmail : undefined;
    let finalMessenger: string | undefined = rawHandle || undefined;

    if (explicitPref === 'sms' || explicitPref === 'email' || explicitPref === 'whatsapp' || explicitPref === 'messenger') {
      preferredChannel = explicitPref as FCommerceOrder['preferredChannel'];
      if (rawChannelLower.includes('pos') || rawChannelLower.includes('offline')) orderChannel = 'POS / Offline Store';
      else if (rawChannelLower.includes('e-commerce') || rawChannelLower.includes('marketplace') || rawChannelLower.includes('daraz') || rawChannelLower.includes('pickaboo')) orderChannel = 'E-Commerce / Marketplace';
      else if (preferredChannel === 'messenger') orderChannel = 'Facebook Messenger';
      else if (preferredChannel === 'sms') orderChannel = 'POS / Offline Store';
      else if (preferredChannel === 'email') orderChannel = 'E-Commerce / Marketplace';
    } else if (rawChannelLower.includes('pos') || rawChannelLower.includes('offline') || rawChannelLower.includes('walk-in')) {
      orderChannel = 'POS / Offline Store';
      preferredChannel = hasPhone ? 'sms' : (hasEmail ? 'email' : 'whatsapp');
      finalWaPhone = undefined;
    } else if (rawChannelLower.includes('daraz') || rawChannelLower.includes('pickaboo') || rawChannelLower.includes('marketplace') || rawChannelLower.includes('e-commerce') || rawChannelLower.includes('shopify')) {
      // Multi-channel Marketplace / Retail Store mix (e.g. Daraz BD / Pickaboo / POS CSV):
      // Demonstrate how customers are reached across Phone SMS (POS/Mobile), Email, and WhatsApp
      const reachMod = idx % 10;
      if (reachMod === 1 || reachMod === 4 || reachMod === 7) {
        // Customer has Phone Number only (no WhatsApp/Facebook) -> Reach via Direct Phone SMS
        orderChannel = reachMod === 1 ? 'POS / Offline Store' : 'E-Commerce / Marketplace';
        preferredChannel = 'sms';
        finalWaPhone = undefined;
      } else if (reachMod === 2 || reachMod === 8) {
        // Customer reached via Personalized Email Offer
        orderChannel = 'E-Commerce / Marketplace';
        preferredChannel = 'email';
        finalWaPhone = undefined;
      } else {
        orderChannel = 'E-Commerce / Marketplace';
        preferredChannel = 'whatsapp';
      }
    } else if (!hasPhone && hasEmail && !rawHandle) {
      orderChannel = 'E-Commerce / Marketplace';
      preferredChannel = 'email';
    } else if (!hasPhone || rawChannelLower.includes('messenger') || rawChannelLower.includes('facebook')) {
      orderChannel = 'Facebook Messenger';
      preferredChannel = 'messenger';
      finalWaPhone = undefined;
      finalMessenger = rawHandle || `m.me/${customerName.toLowerCase().replace(/[^a-z0-9]/g, '.')}.${orderId.toLowerCase().replace(/[^a-z0-9]/g, '')}`;
    }

    return {
      orderId,
      orderDate,
      customerName,
      orderChannel,
      whatsappPhone: finalWaPhone,
      smsPhone: finalSmsPhone,
      customerEmail: finalEmail,
      facebookProfileId: finalMessenger,
      preferredChannel,
      items,
      category,
      quantity,
      unitPrice,
      totalAmountBDT,
      paymentMethod,
      advancePaidBDT,
      dueAmountBDT,
      deliveryDistrict,
      courierPartner,
      deliveryStatus,
      trackingNumber,
      customerNotes: customerNotes || (
        preferredChannel === 'sms'
          ? 'Phone Number on file (No WhatsApp/FB) — Reach via Direct Phone SMS Offer'
          : preferredChannel === 'email'
          ? 'Email Address on file — Reach via Personalized Email Campaign'
          : ''
      ),
    };
  });
}


